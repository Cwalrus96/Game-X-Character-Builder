import { readFile, writeFile } from 'node:fs/promises';
import { buildSchemaDisplayAdapters } from './schema-display-adapters.mjs';
import { techniqueCompatibilityFormula, techniqueBlocksFormula, techniqueNamedFunctionPatches, techniqueNativeFixtures, techniqueDecisionNativeFixtures } from './technique-display-formulas.mjs';
import { GRANT_NAMED_FUNCTIONS, GRANT_NATIVE_FIXTURES } from './grant-display-formulas.mjs';

// Regenerate the checked-in operational manifest; this never writes live Sheets.
const path = new URL('./authoring-formulas.json', import.meta.url);
const manifest = JSON.parse(await readFile(path, 'utf8'));
const adapters = buildSchemaDisplayAdapters();
Object.assign(manifest.cells, adapters.cells, {
  '_Techniques!A1': techniqueCompatibilityFormula(),
  '_TechniqueBlocks!C1': techniqueBlocksFormula(),
  '_TechniqueBlocks!F1': '=CHOOSECOLS(\'_Techniques\'!A1:AJ1000,29,6)',
  'Function_Tests!B8': '=COUNTIF(DATA_GET_COLUMN_BY_NAME("Techniques","skill"),"granted")',
  'Function_Tests!C8': '=LET(source,DATA_IMPORT_SHEET("Techniques"),COUNTIF(CHOOSECOLS(source,XMATCH("selection",INDEX(source,1,0),0)),"granted"))',
  'Function_Tests!B9': '=TECHNIQUE_GET_FIELD("pinning-ammunition","energyCostOptions")',
  'Function_Tests!B10': '=TECHNIQUE_GET_FIELD("dazzling-transformation","skill")',
});
manifest.cells['Function_Tests!B40'] = manifest.cells['Function_Tests!B40']
  .replace('name,XLOOKUP(key,\'_Techniques\'!AC2:AC1000,\'_Techniques\'!A2:A1000),', '')
  .replaceAll('TECHNIQUE_GET_FIELD(name,', 'TECHNIQUE_GET_FIELD(key,');
Object.assign(manifest.values, adapters.values, {
  'Function_Tests!A8': 'Granted Technique selection coverage',
  'Function_Tests!A9': 'Conditional Pinning cost options',
  'Function_Tests!C9': 'pin-only=0; pin-and-attack=3',
  'Function_Tests!A10': 'Granted selection is independent of prerequisites',
  'Function_Tests!C10': 'granted',
  'Function_Tests!K1': 'Native cleanup fixture',
  'Function_Tests!L1': 'Actual', 'Function_Tests!M1': 'Expected', 'Function_Tests!N1': 'Result',
});
manifest.namedFunctions = { ...adapters.namedFunctions, ...Object.fromEntries(
  Object.entries(techniqueNamedFunctionPatches()).map(([name, formula]) => [name, {
    argumentPlaceholders: name === 'TECHNIQUES_CATALOGUE' ? [] : name === 'TECHNIQUE_BLOCKS_BY_SKILL' ? ['skill'] : name === 'TECHNIQUE_GET_FIELD' ? ['name', 'column'] : ['name'], formula,
  }])),
};
Object.assign(manifest.namedFunctions, GRANT_NAMED_FUNCTIONS);
for (const [index, fixture] of techniqueNativeFixtures().entries()) {
  const row = index + 2;
  manifest.values[`Function_Tests!K${row}`] = fixture.name;
  manifest.cells[`Function_Tests!L${row}`] = fixture.formula;
  manifest.values[`Function_Tests!M${row}`] = fixture.expected;
  manifest.cells[`Function_Tests!N${row}`] = `=IF(L${row}=M${row},"PASS","FAIL")`;
}
for (const [index, fixture] of [...techniqueDecisionNativeFixtures(), ...GRANT_NATIVE_FIXTURES].entries()) {
  const row=index+26;
  manifest.values[`Function_Tests!K${row}`]=fixture.name;
  manifest.cells[`Function_Tests!L${row}`]=fixture.formula;
  manifest.values[`Function_Tests!M${row}`]=fixture.expected;
  manifest.cells[`Function_Tests!N${row}`]=`=IF(L${row}=M${row},"PASS","FAIL")`;
}
manifest.values['Function_Tests!A6']='Celestial Knight has no obsolete choose-one children';
manifest.values['Function_Tests!C6']=0;
manifest.cells['Function_Tests!B31']=manifest.cells['Function_Tests!B31'].replaceAll('per Martial Arts rank','per rank').replaceAll('per Henshin Arts rank','per rank');
manifest.description = 'Installed schema-v5 authoring display configuration. Generated by update-authoring-formulas.mjs. Optional source columns become blank compatibility fields; stable keys identify rows. Native calculation and formatted refresh are required. Runtime integration remains deferred.';
for (const sheet of manifest.requiredSheets) {
  if (sheet.title === 'Traits') sheet.purpose = 'Imports the nine-column canonical Traits source; the wider display grid permits optional historical fields.';
  if (sheet.title === '_TechniqueBlocks') sheet.purpose = 'Stable-key Technique rendering pool. F:G project raw keys and formal prerequisites from the optional-header _Techniques adapter.';
}
await writeFile(path, `${JSON.stringify(manifest, null, 2)}\n`);
