// The skill was renamed without changing the ownership of existing choices.
// Keep compatibility at this boundary rather than teaching each consumer aliases.
export const RANGED_WEAPONS_SKILL = "Ranged Weapons";
export const RANGED_WEAPONS_SKILL_KEY = "ranged-weapons";

export function canonicalSkillName(value) {
  const text = String(value ?? "").trim();
  return /^(?:targeting|ranged[ -]weapons)$/i.test(text) ? RANGED_WEAPONS_SKILL : text;
}

export function canonicalSkillKey(value) {
  return canonicalSkillName(value).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

// Persisted keys are identities, not display strings to slugify. Only the
// explicitly renamed key changes; unrelated spelling remains byte-for-byte.
export function canonicalStoredSkillKey(value) {
  return value === "targeting" ? RANGED_WEAPONS_SKILL_KEY : value;
}

export function legacySkillIdentity(value) {
  return canonicalSkillName(value) === RANGED_WEAPONS_SKILL ? "targeting" : value;
}

export function renameSkillText(value) {
  // Only contexts that identify the skill. Aiming names such as "Enhanced
  // Targeting" and ordinary targeting prose are separate concepts.
  return String(value ?? "")
    .replace(/(^|::)Targeting$/g, `$1${RANGED_WEAPONS_SKILL}`)
    .replace(/(\b(?:Melee Weapons|Martial Arts)\s+(?:and|or)\s+)Targeting\b/g, `$1${RANGED_WEAPONS_SKILL}`)
    .replace(/\bTargeting(?=\s*(?:,|and\b|or\b)\s*(?:Melee Weapons|Martial Arts)\b)/g, RANGED_WEAPONS_SKILL)
    .replace(/\bTargeting(?=\s+(?:skills?|weapons?|techniques?)\b)/g, RANGED_WEAPONS_SKILL)
    .replace(/(\b(?:progression|training)\s+in\s+)Targeting\b/gi, `$1${RANGED_WEAPONS_SKILL}`)
    .replace(/(\b(?:name|skill|skillKey|skillKeys)=)Targeting\b/g, `$1${RANGED_WEAPONS_SKILL}`);
}

// Project reviewed, older game data for current UI/rules without changing its
// generated bytes or unrelated persisted entity/choice identities.
export function projectSkillNames(value, field = "") {
  // Authored evidence remains exact even when runtime labels use a renamed skill.
  if (field === "sourceValues") return value;
  if (Array.isArray(value)) return value.map((item) => projectSkillNames(item, field));
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, projectSkillNames(item, key)]));
  }
  if (typeof value !== "string") return value;
  if (field === "skillKey" || field === "skillKeys") return canonicalStoredSkillKey(value);
  if (["skill", "skillName", "combatTechniqueSkill", "combatSkills"].includes(field)) return renameSkillText(canonicalSkillName(value));
  if (/(?:Key|Keys|Id|Ids|Ref)$/.test(field)) return value;
  return renameSkillText(value);
}
